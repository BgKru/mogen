"""Storage key validation and containment (04_backend_specification.md Section 10.10).

A storage key is a relative, forward-slash separated identifier such as
``projects/{project_id}/source/{image_id}.jpg``. Keys are generated by the
backend, never by clients, and every implementation must resolve them beneath
the configured storage root (08_infrastructure.md Section 17.4).

Invalid keys raise ``ValueError``: they signal a programming error, not a
recoverable storage failure.
"""

from __future__ import annotations

from pathlib import Path, PurePosixPath

# Matches the VARCHAR(512) ``storage_key`` columns (05_database_specification).
STORAGE_KEY_MAX_LENGTH = 512

# A NUL byte and a backslash are never valid in a portable key; a colon could
# address a Windows drive or an alternate data stream.
_FORBIDDEN_CHARACTERS = ("\x00", "\\", ":")


def parse_storage_key(key: str) -> PurePosixPath:
    """Validate ``key`` and return it as a canonical relative posix path.

    Accepts a trailing slash because cleanup jobs address directories with
    ``projects/{project_id}/`` (05_database_specification.md Section 12.4).
    """
    if not key:
        raise ValueError("storage key must not be empty")
    if len(key) > STORAGE_KEY_MAX_LENGTH:
        raise ValueError(f"storage key must be at most {STORAGE_KEY_MAX_LENGTH} characters")
    for character in _FORBIDDEN_CHARACTERS:
        if character in key:
            raise ValueError("storage key contains a forbidden character")
    if key.startswith("/"):
        raise ValueError("storage key must be relative")

    stripped = key.rstrip("/")
    for part in stripped.split("/"):
        if part in ("", ".", ".."):
            raise ValueError("storage key contains an invalid path segment")
    return PurePosixPath(stripped)


def resolve_storage_path(root: Path, key: str) -> Path:
    """Resolve a validated key to an absolute path inside ``root``.

    Symlinks are resolved before the containment check, so a link planted in
    the storage tree cannot redirect an operation outside it.
    """
    root_path = Path(root).resolve()
    candidate = (root_path / parse_storage_key(key)).resolve()
    if candidate != root_path and not candidate.is_relative_to(root_path):
        raise ValueError("storage key escapes the storage root")
    return candidate
