"""Image upload, listing, content delivery and deletion (04 Section 10).

The service validates the actual image content, enforces the project's image
rules, writes the file through the storage abstraction and only then persists
metadata. Filesystem and database writes cannot share a transaction, so a
failed database write removes the stored file (05 Section 16.3).

Uploads are serialised by locking the project row. The ``UPLOADING`` status is
set and cleared inside that transaction, so a committed project is never left
in ``UPLOADING`` and a failure leaves the previous status untouched.

Deletion is the mirror image: metadata is removed in one transaction together
with a ``FILE`` cleanup job, and the file itself is deleted later by the
cleanup worker (api_contracts.md Section 8.4).
"""

from __future__ import annotations

import hashlib
import io
import logging
import uuid
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import PurePosixPath
from typing import BinaryIO
from urllib.parse import quote

from PIL import Image, UnidentifiedImageError
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.core.config import Settings
from app.core.exceptions import AppError
from app.db.models import Project, ProjectImage
from app.db.models.enums import (
    CleanupTargetType,
    ImageMimeType,
    ProjectStatus,
    ProjectType,
)
from app.repositories import (
    CleanupJobRepository,
    ImageRepository,
    OutboxRepository,
    ProjectRepository,
    TaskRepository,
)
from app.services.outbox_events import create_cleanup_event
from app.storage import StorageBackend

logger = logging.getLogger(__name__)

# Extension -> actual format, and format -> verified MIME type and key suffix.
ALLOWED_EXTENSIONS = {".jpg": "JPEG", ".jpeg": "JPEG", ".png": "PNG"}
VERIFIED_MIME_TYPES = {
    "JPEG": ImageMimeType.JPEG.value,
    "PNG": ImageMimeType.PNG.value,
}
STORAGE_KEY_SUFFIXES = {"JPEG": "jpg", "PNG": "png"}
# Declared multipart type -> expected actual format.
DECLARED_FORMATS = {
    ImageMimeType.JPEG.value: "JPEG",
    ImageMimeType.PNG.value: "PNG",
}

_MAX_FILENAME_LENGTH = 255
# Fallback download name when the stored filename has no usable ASCII form.
_DOWNLOAD_NAME_FALLBACK = "image"
# Project statuses that mean a generation task owns the source images.
_BLOCKING_STATUSES = (ProjectStatus.PENDING.value, ProjectStatus.PROCESSING.value)
# PostgreSQL SQLSTATE for a foreign key violation.
_FOREIGN_KEY_VIOLATION = "23503"


@dataclass(frozen=True, slots=True)
class ValidatedImage:
    """Decoded image properties that are safe to persist."""

    data: bytes
    mime_type: str
    extension: str
    width: int
    height: int


@dataclass(frozen=True, slots=True)
class ImageContent:
    """An open stored object plus the metadata needed to serve it.

    The stream is owned by the caller, which must close it after delivery.
    """

    image: ProjectImage
    stream: BinaryIO


def clean_filename(filename: str) -> str:
    """Reduce an uploaded filename to a safe, bounded metadata value.

    The filename is metadata only; the stored object name is generated by the
    backend (04 Section 10.3).
    """
    base = filename.replace("\\", "/").rsplit("/", 1)[-1].strip()
    return base[-_MAX_FILENAME_LENGTH:]


def _is_printable_ascii(character: str) -> bool:
    """Return whether a character may appear verbatim in a quoted header value."""
    return 0x20 <= ord(character) < 0x7F and character not in '"\\'


def content_disposition(filename: str) -> str:
    """Build a safe ``inline`` Content-Disposition value for a stored image.

    The stored filename is client-supplied metadata, so it is reduced to its
    base name again and every non-printable or quotation character is replaced.
    That rules out a CR/LF header injection and keeps the quoted string valid
    (RFC 6266). A non-ASCII name is also sent percent-encoded through
    ``filename*`` so the original spelling survives a capable client.
    """
    cleaned = clean_filename(filename)
    ascii_name = "".join(
        character if _is_printable_ascii(character) else "_" for character in cleaned
    ).strip()
    if not ascii_name:
        ascii_name = _DOWNLOAD_NAME_FALLBACK

    disposition = f'inline; filename="{ascii_name}"'
    if cleaned and cleaned != ascii_name:
        disposition += f"; filename*=UTF-8''{quote(cleaned, safe='')}"
    return disposition


def validate_image_bytes(
    *,
    data: bytes,
    filename: str,
    declared_content_type: str | None,
    max_dimension: int,
) -> ValidatedImage:
    """Validate a declared format, the actual decoded format and the dimensions.

    Raises ``AppError`` with the documented status and code: 415 for an
    unsupported declared or actual format, 400 for invalid content and for
    dimensions above ``max_dimension``.
    """
    suffix = PurePosixPath(filename).suffix.lower()
    expected_format = ALLOWED_EXTENSIONS.get(suffix)
    if expected_format is None:
        raise AppError(
            415,
            "INVALID_IMAGE_FORMAT",
            "The uploaded image format is not supported.",
        )

    declared = (declared_content_type or "").split(";", 1)[0].strip().lower()
    declared_format = DECLARED_FORMATS.get(declared)
    if declared_format is None:
        raise AppError(
            415,
            "INVALID_IMAGE_FORMAT",
            "The uploaded image format is not supported.",
        )

    if not data:
        raise AppError(400, "INVALID_IMAGE_CONTENT", "The uploaded file is empty.")

    try:
        with Image.open(io.BytesIO(data)) as image:
            image.load()
            actual_format = image.format
            width, height = image.size
    except Image.DecompressionBombError as exc:
        raise AppError(
            400,
            "IMAGE_DIMENSIONS_EXCEEDED",
            "The uploaded image dimensions exceed the allowed limit.",
        ) from exc
    except (UnidentifiedImageError, OSError, SyntaxError, ValueError) as exc:
        raise AppError(
            400,
            "INVALID_IMAGE_CONTENT",
            "The uploaded file is not a valid image.",
        ) from exc

    if actual_format not in VERIFIED_MIME_TYPES or actual_format != expected_format:
        raise AppError(
            415,
            "INVALID_IMAGE_FORMAT",
            "The uploaded image format is not supported.",
        )
    if declared_format != actual_format:
        raise AppError(
            415,
            "INVALID_IMAGE_FORMAT",
            "The declared media type does not match the uploaded image.",
        )
    if max(width, height) > max_dimension:
        raise AppError(
            400,
            "IMAGE_DIMENSIONS_EXCEEDED",
            "The uploaded image dimensions exceed the allowed limit.",
        )

    return ValidatedImage(
        data=data,
        mime_type=VERIFIED_MIME_TYPES[actual_format],
        extension=STORAGE_KEY_SUFFIXES[actual_format],
        width=width,
        height=height,
    )


def _project_not_found() -> AppError:
    return AppError(404, "PROJECT_NOT_FOUND", "Project not found.")


def _image_not_found() -> AppError:
    return AppError(404, "IMAGE_NOT_FOUND", "Image not found.")


def _image_referenced() -> AppError:
    return AppError(
        409,
        "IMAGE_REFERENCED",
        "The image is referenced by generation history and cannot be deleted.",
    )


class ImageService:
    """Upload, list, deliver and delete the source photographs of a project."""

    def __init__(
        self,
        session: Session,
        settings: Settings,
        storage: StorageBackend,
    ) -> None:
        self._db = session
        self._settings = settings
        self._storage = storage
        self._projects = ProjectRepository(session)
        self._images = ImageRepository(session)
        self._tasks = TaskRepository(session)
        self._cleanup_jobs = CleanupJobRepository(session)
        self._outbox = OutboxRepository(session)

    def upload_image(
        self,
        *,
        user_id: uuid.UUID,
        project_id: uuid.UUID,
        filename: str,
        content_type: str | None,
        data: bytes,
    ) -> ProjectImage:
        """Validate and store one photograph, then persist its metadata."""
        project = self._projects.get_active_for_update(project_id)
        if project is None or project.user_id != user_id:
            raise _project_not_found()
        self._ensure_upload_allowed(project)

        max_bytes = self._settings.max_upload_size_mb * 1024 * 1024
        if len(data) > max_bytes:
            raise AppError(413, "IMAGE_TOO_LARGE", "The uploaded image exceeds the size limit.")

        safe_filename = clean_filename(filename)
        validated = validate_image_bytes(
            data=data,
            filename=safe_filename,
            declared_content_type=content_type,
            max_dimension=self._settings.max_image_dimension,
        )
        self._ensure_count_allowed(project)

        image_id = uuid.uuid4()
        storage_key = f"projects/{project_id}/source/{image_id}.{validated.extension}"
        position = self._images.next_position(project_id)
        self._projects.set_status(project, ProjectStatus.UPLOADING.value)

        stored = False
        try:
            self._storage.save(validated.data, storage_key)
            stored = True
            image = self._images.create(
                image_id=image_id,
                project_id=project_id,
                original_filename=safe_filename,
                storage_key=storage_key,
                mime_type=validated.mime_type,
                file_size_bytes=len(validated.data),
                sha256=hashlib.sha256(validated.data).hexdigest(),
                width=validated.width,
                height=validated.height,
                position=position,
            )
            self._projects.set_status(project, ProjectStatus.CREATED.value)
            self._db.commit()
        except Exception:
            # The database and the filesystem cannot commit together: drop the
            # file so the project never keeps a record-less object (05 16.3).
            self._db.rollback()
            if stored:
                self._delete_quietly(storage_key, project_id)
            raise
        return image

    def list_images(self, *, user_id: uuid.UUID, project_id: uuid.UUID) -> Sequence[ProjectImage]:
        """Return a project's images in their upload order."""
        project = self._projects.get_active_for_user(project_id, user_id)
        if project is None:
            raise _project_not_found()
        return self._images.list_for_project(project_id)

    def open_image_content(
        self, *, user_id: uuid.UUID, project_id: uuid.UUID, image_id: uuid.UUID
    ) -> ImageContent:
        """Open one image's stored bytes after verifying project ownership.

        A missing project or image row is reported as 404. A metadata row whose
        stored object has disappeared is also reported as 404
        ``IMAGE_NOT_FOUND``: the request cannot be satisfied and retrying
        cannot fix it, so a 5xx would be misleading. It is logged at error
        level because it signals a data inconsistency (05 Section 16.3).

        A filesystem failure keeps the storage layer's 503
        ``STORAGE_UNAVAILABLE``, the same mapping the result download uses
        (api_contracts.md Sections 8.3 and 10.2).
        """
        project = self._projects.get_active_for_user(project_id, user_id)
        if project is None:
            raise _project_not_found()
        image = self._images.get_for_project(image_id, project_id)
        if image is None:
            raise _image_not_found()

        try:
            stream = self._storage.open(image.storage_key)
        except FileNotFoundError as exc:
            logger.error(
                "image_content_missing",
                extra={
                    "operation": "image_content",
                    "project_id": str(project_id),
                    "image_id": str(image_id),
                },
            )
            raise _image_not_found() from exc
        return ImageContent(image=image, stream=stream)

    def delete_image(
        self, *, user_id: uuid.UUID, project_id: uuid.UUID, image_id: uuid.UUID
    ) -> None:
        """Delete one source image and schedule its stored file for cleanup.

        One transaction removes the metadata and records a ``FILE`` cleanup job
        for the exact storage key, so the file is deleted asynchronously by the
        cleanup worker instead of inside the request (api_contracts 8.4;
        05 Section 12.4). The project row lock serialises the operation with
        uploads and with generation task creation.

        Deletion is refused with 409 while a generation task references the
        image or while the project state means generation owns its sources.
        The reference check and the database ``RESTRICT`` foreign key agree;
        the constraint is still translated so a concurrent snapshot insert
        cannot surface as a 500.
        """
        project = self._projects.get_active_for_update(project_id)
        if project is None or project.user_id != user_id:
            raise _project_not_found()

        image = self._images.get_for_project(image_id, project_id)
        if image is None:
            raise _image_not_found()
        if self._tasks.is_image_referenced(image.id):
            raise _image_referenced()
        self._ensure_deletion_allowed(project)

        if self._cleanup_jobs.get_active_for_target(image.storage_key) is None:
            job = self._cleanup_jobs.create(
                project_id=project_id,
                storage_key=image.storage_key,
                target_type=CleanupTargetType.FILE.value,
            )
            # Job and dispatch event commit in one transaction; the dispatcher
            # publishes cleanup.requested instead of the worker waiting for the
            # next poll.
            create_cleanup_event(self._outbox, job)
        try:
            # The repository flushes, so the RESTRICT foreign key can fail here
            # rather than at commit.
            self._images.delete(image)
            self._db.commit()
        except IntegrityError as exc:
            self._db.rollback()
            if getattr(exc.orig, "sqlstate", None) != _FOREIGN_KEY_VIOLATION:
                raise
            raise _image_referenced() from exc

    def _ensure_deletion_allowed(self, project: Project) -> None:
        """Reject deletion while a generation task owns the source images."""
        self._ensure_source_modification_allowed(project, action="deleting")

    def _ensure_upload_allowed(self, project: Project) -> None:
        """Reject uploads while a generation task owns the project's images."""
        self._ensure_source_modification_allowed(project, action="uploading")

    def _ensure_source_modification_allowed(self, project: Project, *, action: str) -> None:
        """Reject a source change while a generation task owns the images."""
        if (
            project.status in _BLOCKING_STATUSES
            or self._tasks.get_active_for_project(project.id) is not None
        ):
            raise AppError(
                409,
                "INVALID_PROJECT_STATE",
                f"The project state does not permit {action} images.",
            )

    def _ensure_count_allowed(self, project: Project) -> None:
        count = self._images.count_for_project(project.id)
        if project.type == ProjectType.OBJECT.value and count >= 1:
            raise AppError(
                409,
                "IMAGE_COUNT_EXCEEDED",
                "An OBJECT project accepts exactly one source image.",
            )
        if project.type == ProjectType.SCENE.value and count >= self._settings.max_scene_images:
            raise AppError(
                409,
                "IMAGE_COUNT_EXCEEDED",
                f"A SCENE project accepts at most {self._settings.max_scene_images} source images.",
            )

    def _delete_quietly(self, storage_key: str, project_id: uuid.UUID) -> None:
        """Best-effort removal; a leftover object must not mask the real error."""
        try:
            self._storage.delete(storage_key)
        except Exception:
            logger.exception(
                "upload_file_cleanup_failed",
                extra={"operation": "image_upload", "project_id": str(project_id)},
            )
